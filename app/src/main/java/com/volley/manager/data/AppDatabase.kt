private val MIGRATION_6_7 = object : Migration(6, 7) {
    override fun migrate(db: SupportSQLiteDatabase) {
        db.execSQL("ALTER TABLE events ADD COLUMN seriesId TEXT")

        // Existing events were never linked together, so recover the grouping
        // heuristically: events sharing the same title/type/duration and starting
        // exactly one week apart are treated as the same recurring series.
        data class Row(val id: Long, val title: String, val type: String, val duration: Int, val startsAt: Long)
        val rows = mutableListOf<Row>()
        db.query("SELECT id, title, type, durationMinutes, startsAt FROM events ORDER BY startsAt").use { cursor ->
            val idIdx = cursor.getColumnIndexOrThrow("id")
            val titleIdx = cursor.getColumnIndexOrThrow("title")
            val typeIdx = cursor.getColumnIndexOrThrow("type")
            val durationIdx = cursor.getColumnIndexOrThrow("durationMinutes")
            val startsAtIdx = cursor.getColumnIndexOrThrow("startsAt")
            while (cursor.moveToNext()) {
                rows.add(
                    Row(
                        cursor.getLong(idIdx), cursor.getString(titleIdx), cursor.getString(typeIdx),
                        cursor.getInt(durationIdx), cursor.getLong(startsAtIdx)
                    )
                )
            }
        }

        val oneWeekMs = 7L * 24 * 60 * 60 * 1000
        val toleranceMs = 60L * 60 * 1000 // tolerate DST shifts around the exact week mark
        rows.groupBy { Triple(it.title, it.type, it.duration) }.values.forEach { group ->
            var currentSeriesId: String? = null
            var previousStartsAt: Long? = null
            group.sortedBy { it.startsAt }.forEach { row ->
                val continuesSeries = previousStartsAt != null &&
                    kotlin.math.abs((row.startsAt - previousStartsAt!!) - oneWeekMs) <= toleranceMs
                if (!continuesSeries) currentSeriesId = java.util.UUID.randomUUID().toString()
                db.execSQL("UPDATE events SET seriesId = ? WHERE id = ?", arrayOf(currentSeriesId, row.id))
                previousStartsAt = row.startsAt
            }
        }
    }
}

@Database(entities = [Player::class, VolleyEvent::class, EventGuest::class, Attendance::class, Absence::class, Feedback::class], version = 7, exportSchema = false)
@TypeConverters(Converters::class)
abstract class AppDatabase : RoomDatabase() {
    abstract fun players(): PlayerDao
    abstract fun events(): EventDao
    abstract fun eventGuests(): EventGuestDao
    abstract fun attendance(): AttendanceDao
    abstract fun absences(): AbsenceDao
    abstract fun feedback(): FeedbackDao

    companion object {
        fun create(context: Context): AppDatabase = Room.databaseBuilder(
            context, AppDatabase::class.java, "volley-manager.db"
        ).addMigrations(MIGRATION_4_5, MIGRATION_5_6, MIGRATION_6_7).build()
    }
}

class Converters {
    @TypeConverter fun eventType(value: EventType) = value.name
    @TypeConverter fun eventType(value: String) = EventType.valueOf(value)
    @TypeConverter fun attendanceStatus(value: AttendanceStatus) = value.name
    @TypeConverter fun attendanceStatus(value: String) = AttendanceStatus.valueOf(value)
}
