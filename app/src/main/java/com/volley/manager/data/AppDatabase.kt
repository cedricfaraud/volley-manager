package com.volley.manager.data

import android.content.Context
import androidx.room.*
import androidx.room.migration.Migration
import androidx.sqlite.db.SupportSQLiteDatabase
import kotlinx.coroutines.flow.Flow

enum class EventType { TRAINING, MATCH, EXCEPTIONAL }
enum class AttendanceStatus { PRESENT, ABSENT, LATE, EXCUSED }

@Entity(tableName = "players")
data class Player(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val firstName: String,
    val lastName: String,
    val age: Int,
    val position: String,
    val isGuest: Boolean = false,
    val email: String = "",
    val phone: String = "",
    val heightCm: Int? = null,
    val jerseyNumber: Int? = null,
    val notes: String = "",
    val serviceRating: Int = 0,
    val receptionRating: Int = 0,
    val settingRating: Int = 0,
    val attackRating: Int = 0,
    val blockRating: Int = 0,
    val defenseRating: Int = 0,
    val motivationRating: Int = 0,
    val techniqueRating: Int = 0
)

@Entity(tableName = "events")
data class VolleyEvent(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val title: String,
    val type: EventType,
    val startsAt: Long,
    val durationMinutes: Int,
    val recurrenceDays: String = "",
    val recurrenceEndAt: Long? = null,
    val cancelled: Boolean = false,
    // Groups every occurrence generated by the same "add event" call (a recurring
    // series or a single standalone event) so a whole series can be targeted at once,
    // e.g. to delete "this and future occurrences".
    val seriesId: String? = null
)

@Entity(tableName = "event_guests", primaryKeys = ["playerId", "eventId"])
data class EventGuest(val playerId: Long, val eventId: Long)

@Entity(tableName = "attendance", primaryKeys = ["playerId", "eventId"])
data class Attendance(
    val playerId: Long,
    val eventId: Long,
    val status: AttendanceStatus = AttendanceStatus.PRESENT
)

@Entity(tableName = "absences")
data class Absence(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val playerId: Long,
    val startsAt: Long,
    val endsAt: Long,
    val reason: String
)

@Entity(tableName = "feedback")
data class Feedback(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val category: String,
    val title: String,
    val details: String,
    val createdAt: Long = System.currentTimeMillis()
)

@Dao
interface PlayerDao {
    @Query("SELECT * FROM players ORDER BY lastName, firstName")
    fun observeAll(): Flow<List<Player>>
    @Insert suspend fun insert(player: Player): Long
    @Insert suspend fun insertAll(players: List<Player>)
    @Update suspend fun update(player: Player)
    @Delete suspend fun delete(player: Player)
    @Query("DELETE FROM players") suspend fun deleteAll()
}

@Dao
interface EventDao {
    @Query("SELECT * FROM events ORDER BY startsAt")
    fun observeAll(): Flow<List<VolleyEvent>>
    @Insert suspend fun insert(event: VolleyEvent)
    @Insert suspend fun insertAll(events: List<VolleyEvent>)
    @Update suspend fun update(event: VolleyEvent)
    @Query("DELETE FROM events") suspend fun deleteAll()
    @Query("DELETE FROM events WHERE id = :id") suspend fun deleteById(id: Long)
    @Query("DELETE FROM events WHERE seriesId = :seriesId AND startsAt >= :fromStartsAt")
    suspend fun deleteSeriesFrom(seriesId: String, fromStartsAt: Long)
}

@Dao
interface EventGuestDao {
    @Query("SELECT * FROM event_guests")
    fun observeAll(): Flow<List<EventGuest>>
    @Insert(onConflict = OnConflictStrategy.REPLACE) suspend fun add(guest: EventGuest)
    @Insert(onConflict = OnConflictStrategy.REPLACE) suspend fun insertAll(guests: List<EventGuest>)
    @Delete suspend fun remove(guest: EventGuest)
    @Query("DELETE FROM event_guests") suspend fun deleteAll()
    @Query("DELETE FROM event_guests WHERE eventId = :eventId") suspend fun deleteForEvent(eventId: Long)
    @Query("DELETE FROM event_guests WHERE eventId IN (SELECT id FROM events WHERE seriesId = :seriesId AND startsAt >= :fromStartsAt)")
    suspend fun deleteForSeriesFrom(seriesId: String, fromStartsAt: Long)
}

@Dao
interface AttendanceDao {
    @Query("SELECT * FROM attendance")
    fun observeAll(): Flow<List<Attendance>>
    @Insert(onConflict = OnConflictStrategy.REPLACE) suspend fun save(attendance: Attendance)
    @Insert(onConflict = OnConflictStrategy.REPLACE) suspend fun insertAll(attendance: List<Attendance>)
    @Query("DELETE FROM attendance") suspend fun deleteAll()
    @Query("DELETE FROM attendance WHERE eventId = :eventId") suspend fun deleteForEvent(eventId: Long)
    @Query("DELETE FROM attendance WHERE eventId IN (SELECT id FROM events WHERE seriesId = :seriesId AND startsAt >= :fromStartsAt)")
    suspend fun deleteForSeriesFrom(seriesId: String, fromStartsAt: Long)
}

@Dao
interface AbsenceDao {
    @Insert suspend fun insert(absence: Absence)
    @Insert suspend fun insertAll(absences: List<Absence>)
    @Query("SELECT * FROM absences")
    fun observeAll(): Flow<List<Absence>>
    @Query("DELETE FROM absences") suspend fun deleteAll()
}

@Dao
interface FeedbackDao {
    @Query("SELECT * FROM feedback ORDER BY createdAt DESC")
    fun observeAll(): Flow<List<Feedback>>
    @Insert suspend fun insert(feedback: Feedback)
    @Insert suspend fun insertAll(feedback: List<Feedback>)
    @Query("DELETE FROM feedback") suspend fun deleteAll()
}

